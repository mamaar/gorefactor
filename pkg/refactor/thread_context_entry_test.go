package refactor

import (
	"strings"
	"testing"

	"github.com/mamaar/gorefactor/pkg/types"
)

const entryPkg = "example.com/threadtest"

func threadScoped(t *testing.T, files map[string]string, fn string) (*types.RefactoringPlan, string) {
	t.Helper()
	eng, dir := loadConfigsEngine(t, files)

	plan, err := eng.ThreadContextAcrossConfigs(types.ThreadContextRequest{FunctionName: fn, SourceFile: "main.go", EntryPackage: entryPkg})
	if err != nil {
		t.Fatal(err)
	}

	err = eng.ExecutePlan(plan)
	if err != nil {
		t.Fatal(err)
	}

	return plan, dir
}

func TestThreadContextEntry_CallerOutsideTheEntryKeepsItsSignature(t *testing.T) {
	plan, dir := threadScoped(t, map[string]string{
		"main.go":      "package main\n\nfunc S() {}\n\nfunc A() { S() }\n\nfunc B() { S() }\n\nfunc main() { A() }\n",
		"main_test.go": "package main\n\nfunc helper() { S() }\n",
	}, "S")

	assertOnce(t, dir, "main.go", "func A(ctx context.Context) { S(ctx) }")
	assertOnce(t, dir, "main.go", "func B() { S(context.TODO()) }")
	assertOnce(t, dir, "main_test.go", "func helper(ctx context.Context) { S(ctx) }")

	if len(plan.SkippedSites) != 1 || !strings.HasPrefix(plan.SkippedSites[0].Reason, "outside entry:") || plan.SkippedSites[0].Snippet != "B" {
		t.Errorf("skipped = %+v, want B outside entry", plan.SkippedSites)
	}

	vetBuilds(t, dir, linuxBuild)
}

func TestThreadContextEntry_UnreachedImplementationOfAReachedInterfaceMethodStillChanges(t *testing.T) {
	_, dir := threadScoped(t, map[string]string{
		"main.go": "package main\n\nfunc S() {}\n\ntype I interface{ M() }\n\ntype X struct{}\n\nfunc (X) M() { S() }\n\ntype Y struct{}\n\nfunc (Y) M() {}\n\nfunc main() {\n\tvar i I = X{}\n\ti.M()\n}\n",
	}, "S")

	assertOnce(t, dir, "main.go", "func (Y) M(ctx context.Context) {}")
	vetBuilds(t, dir, linuxBuild)
}

