// facadeMarker identifies a facade file written by gorefactor; only such files
// are replaced or deleted when a facade is regenerated.
const facadeMarker = "This file was generated by gorefactor."

// facadeDecl is one top-level exported declaration of a source package.
type facadeDecl struct {
	name    string
	keyword string // "var", "const" or "type"
}

// facadeKey is the constraint under which a facade file is built, copied from
// the source files declaring its symbols.
type facadeKey struct {
	expr   string // //go:build expression, empty when unconstrained
	suffix string // GOOS/GOARCH file name suffix
}

// facadeFile accumulates the re-exports that share one constraint.
type facadeFile struct {
	key   facadeKey
	decls map[string]map[facadeDecl]bool // source import path -> declarations
}

// facadeBuilder groups the exported symbols of source packages by the
// constraint of the file declaring them.
type facadeBuilder struct {
	files map[facadeKey]*facadeFile
	// unconstrained is set when a source file is built under every configuration.
	unconstrained bool
}

func newFacadeBuilder() *facadeBuilder {
	return &facadeBuilder{files: make(map[facadeKey]*facadeFile)}
}

// add records the exported symbols of the non-test files of the package at
// importPath, whatever their build constraints. keep filters by symbol name.
func (b *facadeBuilder) add(importPath string, files []*analysis.SourceFile, keep func(string) bool) {
	for _, f := range files {
		if f.AST == nil {
			continue
		}

		key := facadeKeyOf(f)
		if key == (facadeKey{}) {
			b.unconstrained = true
		}

		for _, d := range exportedDecls(f.AST) {
			if !keep(d.name) {
				continue
			}

			ff := b.files[key]
			if ff == nil {
				ff = &facadeFile{key: key, decls: make(map[string]map[facadeDecl]bool)}
				b.files[key] = ff
			}

			if ff.decls[importPath] == nil {
				ff.decls[importPath] = make(map[facadeDecl]bool)
			}

			ff.decls[importPath][d] = true
		}
	}
}

func (b *facadeBuilder) empty() bool { return len(b.files) == 0 }

func facadeKeyOf(f *analysis.SourceFile) facadeKey {
	c := analysis.ConstraintOf(f)

	expr := c.Expr
	if c.Cgo {
		cgo := &constraint.TagExpr{Tag: "cgo"}
		if expr == nil {
			expr = cgo
		} else {
			expr = &constraint.AndExpr{X: expr, Y: cgo}
		}
	}

	key := facadeKey{suffix: c.Suffix}
	if expr != nil {
		key.expr = expr.String()
	}

	return key
}

// exportedDecls lists the top-level exported declarations a facade can
// re-export: generic functions and types cannot be aliased and are left out.
func exportedDecls(f *ast.File) []facadeDecl {
	var out []facadeDecl

	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil && d.Name.IsExported() && d.Type.TypeParams == nil {
				out = append(out, facadeDecl{d.Name.Name, "var"})
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() && s.TypeParams == nil {
						out = append(out, facadeDecl{s.Name.Name, "type"})
					}
				case *ast.ValueSpec:
					keyword := "var"
					if d.Tok == token.CONST {
						keyword = "const"
					}

					for _, n := range s.Names {
						if n.IsExported() {
							out = append(out, facadeDecl{n.Name, keyword})
						}
					}
				}
			}
		}
	}

	return out
}

var nonWord = regexp.MustCompile(`[^a-z0-9]+`)

// facadeFileName returns a name for the facade file of key that go/build
// resolves to the same constraint, and that is not in taken.
func facadeFileName(key facadeKey, taken map[string]bool) string {
	words := ""

	if key.expr != "" {
		r := strings.NewReplacer("&&", " and ", "||", " or ", "!", " not ")
		words = strings.Trim(nonWord.ReplaceAllString(r.Replace(strings.ToLower(key.expr)), "_"), "_")
	}

	for n := 1; ; n++ {
		name := "facade"

		w := words
		if n > 1 {
			w = fmt.Sprintf("%s_%d", words, n)
		}

		if w != "" {
			name += "_" + strings.TrimPrefix(w, "_")
		}

		switch {
		case key.suffix != "":
			name += "_" + key.suffix
		case words != "":
			// A trailing GOOS or GOARCH word would otherwise constrain the file.
			name += "_tags"
		}

		name += ".go"
		if !taken[name] {
			return name
		}
	}
}

// render returns the source of the facade file for pkgName.
func (ff *facadeFile) render(pkgName string) string {
	var sb strings.Builder
	if ff.key.expr != "" {
		fmt.Fprintf(&sb, "//go:build %s\n\n", ff.key.expr)
	} else if ff.key.suffix == "" {
		fmt.Fprintf(&sb, "// Package %s provides a facade for accessing related functionality.\n", pkgName)
	}

	fmt.Fprintf(&sb, "// %s\npackage %s\n\n", facadeMarker, pkgName)

	imports := slices.Sorted(maps.Keys(ff.decls))
	if len(imports) > 0 {
		sb.WriteString("import (\n")

		for _, imp := range imports {
			fmt.Fprintf(&sb, "\t%q\n", imp)
		}

		sb.WriteString(")\n\n")
	}

	for _, imp := range imports {
		decls := slices.SortedFunc(maps.Keys(ff.decls[imp]), func(a, b facadeDecl) int { return strings.Compare(a.name, b.name) })
		for _, d := range decls {
			fmt.Fprintf(&sb, "// %s is re-exported from %s\n", d.name, imp)

			if d.keyword == "type" {
				fmt.Fprintf(&sb, "type %s = %s.%s\n\n", d.name, path.Base(imp), d.name)
			} else {
				fmt.Fprintf(&sb, "%s %s = %s.%s\n\n", d.keyword, d.name, path.Base(imp), d.name)
			}
		}
	}

	return sb.String()
}

// planFacadeDir adds the changes that make the generated facade files of dir
// exactly the files of b: new ones are created, changed ones replaced whole,
// and generated ones no longer needed deleted. A file that gorefactor did not
// generate is never touched; one standing where a facade file belongs is an error.
func (b *facadeBuilder) planFacadeDir(plan *types.RefactoringPlan, tree *analysis.SourceTree, dir, pkgName string) error {
	// An unconstrained source file means the package builds everywhere, so the
	// facade must too, even when only constrained files export anything.
	if b.unconstrained && !b.empty() && b.files[facadeKey{}] == nil {
		b.files[facadeKey{}] = &facadeFile{decls: make(map[string]map[facadeDecl]bool)}
	}

	existing := make(map[string]*analysis.SourceFile)
	for _, f := range tree.Dir(dir) {
		existing[f.Name] = f
	}

	keys := slices.SortedFunc(maps.Keys(b.files), func(x, y facadeKey) int {
		return strings.Compare(x.expr+"\x00"+x.suffix, y.expr+"\x00"+y.suffix)
	})

	wanted := make(map[string]bool)
	for _, key := range keys {
		name := facadeFileName(key, wanted)
		wanted[name] = true
		file := filepath.Join(dir, name)
		content := b.files[key].render(pkgName)

		old, found := existing[name]
		switch {
		case !found:
			plan.Changes = append(plan.Changes, types.Change{File: file, NewText: content,
				Description: fmt.Sprintf("Create facade file %s", file)})
		case !isGeneratedFacade(old):
			return fmt.Errorf("%s exists and was not generated by gorefactor; rename or remove it", file)
		case string(old.Content) == content:
			continue
		default:
			plan.Changes = append(plan.Changes, types.Change{File: file, End: len(old.Content),
				OldText: string(old.Content), NewText: content,
				Description: fmt.Sprintf("Regenerate facade file %s", file)})
		}

		plan.AffectedFiles = append(plan.AffectedFiles, file)
	}

	for name, f := range existing {
		if wanted[name] || !isGeneratedFacade(f) {
			continue
		}

		plan.Changes = append(plan.Changes, types.Change{File: f.Path, Delete: true,
			Description: fmt.Sprintf("Remove stale facade file %s", f.Path)})
		plan.AffectedFiles = append(plan.AffectedFiles, f.Path)
	}

	return nil
}

func isGeneratedFacade(f *analysis.SourceFile) bool {
	return strings.HasPrefix(f.Name, "facade") && strings.Contains(string(f.Content), facadeMarker)
}

// nonTestFiles returns the files of a directory that belong to the package
// itself, whatever their build constraints.
func nonTestFiles(files []*analysis.SourceFile) []*analysis.SourceFile {
	return slices.DeleteFunc(slices.Clone(files), func(f *analysis.SourceFile) bool {
		return strings.HasSuffix(f.Name, "_test.go")
	})
}

// packageFiles returns the parsed non-test files of the package a directory
// builds, and its name: files no build configuration includes, and files of
// another package (such as a go:generate main), are left out. The name is the
// most common package clause among the rest.
func packageFiles(files []*analysis.SourceFile, uncovered map[string]bool) (string, []*analysis.SourceFile) {
	candidates := slices.DeleteFunc(nonTestFiles(files), func(f *analysis.SourceFile) bool {
		return f.AST == nil || uncovered[f.Path]
	})
	count := make(map[string]int)
	name := ""

	for _, f := range candidates {
		n := f.AST.Name.Name

		count[n]++
		if count[n] > count[name] {
			name = n
		}
	}

	return name, slices.DeleteFunc(candidates, func(f *analysis.SourceFile) bool { return f.AST.Name.Name != name })
}

// uncoveredSet returns the paths of the files no build configuration includes.
func uncoveredSet(c analysis.Covering) map[string]bool {
	out := make(map[string]bool, len(c.Uncovered))
	for _, u := range c.Uncovered {
		out[u.Path] = true
	}

	return out
}

// importPathDirs maps the import path of every source-tree directory to it.
func importPathDirs(ws *types.Workspace, tree *analysis.SourceTree) map[string]string {
	out := make(map[string]string)

	for _, dir := range tree.Dirs() {
		ip := packagePathToImportPath(ws, dir)
		if ip != "" {
			out[ip] = dir
		}
	}

	return out
}

// isFacadePackage reports whether every non-trivial line of the files is a
// re-export declaration (type/var/const X = pkg.X).
func isFacadePackage(files []*analysis.SourceFile) bool {
	if len(files) == 0 {
		return false
	}

	for _, file := range files {
		inImports := false

		for line := range strings.SplitSeq(string(file.Content), "\n") {
			trimmed := strings.TrimSpace(line)
			switch {
			case inImports:
				inImports = trimmed != ")"
				continue
			case trimmed == "import (":
				inImports = true
				continue
			case trimmed == "", strings.HasPrefix(trimmed, "//"),
				strings.HasPrefix(trimmed, "package "),
				strings.HasPrefix(trimmed, "import "):
				continue
			}

			isReexport := (strings.HasPrefix(trimmed, "type ") || strings.HasPrefix(trimmed, "var ") || strings.HasPrefix(trimmed, "const ")) &&
				strings.Contains(trimmed, " = ")
			if !isReexport {
				return false
			}
		}
	}

	return true
}

// GenerateFacadesOperation implements auto-generating facades
type GenerateFacadesOperation struct {
	Request types.GenerateFacadesRequest
	// Sources holds every .go file of the workspace, so symbols declared in
	// files the loaded build configuration excludes are re-exported too.
	Sources *analysis.SourceTree
	// Covering names the files no build configuration includes.
	Covering analysis.Covering
}

func (op *GenerateFacadesOperation) Type() types.OperationType {
	return types.GenerateFacadesOperation
}

func (op *GenerateFacadesOperation) Description() string {
	return fmt.Sprintf("Generate facades for modules in %s", op.Request.ModulesDir)
}

func (op *GenerateFacadesOperation) Validate(ws *types.Workspace) error {
	if op.Request.ModulesDir == "" {
		return fmt.Errorf("modules directory cannot be empty")
	}

	if op.Request.TargetDir == "" {
		return fmt.Errorf("target directory cannot be empty")
	}

	return nil
}

func (op *GenerateFacadesOperation) Execute(ws *types.Workspace) (*types.RefactoringPlan, error) {
	plan := &types.RefactoringPlan{
		Operations:    []types.Operation{op},
		Changes:       make([]types.Change, 0),
		AffectedFiles: make([]string, 0),
		Reversible:    true,
	}

	keep := func(name string) bool {
		if len(op.Request.ExportTypes) == 0 {
			return true
		}

		return slices.ContainsFunc(op.Request.ExportTypes, func(et string) bool {
			return strings.Contains(strings.ToLower(name), strings.ToLower(et))
		})
	}
	modulesDirAbs := filepath.Join(ws.RootPath, op.Request.ModulesDir)
	uncovered := uncoveredSet(op.Covering)

	for _, dir := range op.Sources.Dirs() {
		if !strings.HasPrefix(dir, modulesDirAbs) || strings.Contains(dir, string(filepath.Separator)+"testdata") {
			continue
		}

		files, err := sourceFilesOf(op.Sources, dir)
		if err != nil {
			return nil, err
		}

		name, files := packageFiles(files, uncovered)

		importPath := packagePathToImportPath(ws, dir)
		if name == "" || name == "main" || importPath == "" {
			continue
		}

		b := newFacadeBuilder()
		b.add(importPath, files, keep)

		if b.empty() {
			continue
		}

		target := filepath.Join(ws.RootPath, op.Request.TargetDir, name)
		if err := b.planFacadeDir(plan, op.Sources, target, name); err != nil {
			return nil, err
		}
	}

	return plan, nil
}

// UpdateFacadesOperation implements updating existing facades
type UpdateFacadesOperation struct {
	Request types.UpdateFacadesRequest
	// Sources holds every .go file of the workspace, so facade packages and the
	// packages they re-export are read whatever their build constraints.
	Sources *analysis.SourceTree
	// Covering names the files no build configuration includes.
	Covering analysis.Covering
}

func (op *UpdateFacadesOperation) Type() types.OperationType {
	return types.UpdateFacadesOperation
}

func (op *UpdateFacadesOperation) Description() string {
	return fmt.Sprintf("Update facades in %s", strings.Join(op.Request.FacadePackages, ", "))
}

func (op *UpdateFacadesOperation) Validate(ws *types.Workspace) error {
	if len(op.Request.FacadePackages) == 0 && !op.Request.AutoDetect {
		return fmt.Errorf("no facade packages specified and auto_detect is false")
	}

	return nil
}

func (op *UpdateFacadesOperation) Execute(ws *types.Workspace) (*types.RefactoringPlan, error) {
	plan := &types.RefactoringPlan{
		Operations:    []types.Operation{op},
		Changes:       make([]types.Change, 0),
		AffectedFiles: make([]string, 0),
		Reversible:    true,
	}

	var facadeDirs []string

	for _, p := range op.Request.FacadePackages {
		if !filepath.IsAbs(p) {
			p = filepath.Join(ws.RootPath, p)
		}

		facadeDirs = append(facadeDirs, filepath.Clean(p))
	}

	if op.Request.AutoDetect {
		for _, dir := range op.Sources.Dirs() {
			if isFacadePackage(nonTestFiles(op.Sources.Dir(dir))) && !slices.Contains(facadeDirs, dir) {
				facadeDirs = append(facadeDirs, dir)
			}
		}
	}

	sourceDirs := importPathDirs(ws, op.Sources)
	uncovered := uncoveredSet(op.Covering)
	keepAll := func(string) bool { return true }

	for _, facadeDir := range facadeDirs {
		files, err := sourceFilesOf(op.Sources, facadeDir)
		if err != nil {
			return nil, err
		}

		pkgName, files := packageFiles(files, uncovered)

		b := newFacadeBuilder()

		for _, f := range files {
			for _, imp := range f.AST.Imports {
				importPath := strings.Trim(imp.Path.Value, `"`)

				dir, ok := sourceDirs[importPath]
				if !ok {
					continue
				}

				srcFiles, err := sourceFilesOf(op.Sources, dir)
				if err != nil {
					return nil, err
				}

				_, srcFiles = packageFiles(srcFiles, uncovered)
				b.add(importPath, srcFiles, keepAll)
			}
		}

		if err := b.planFacadeDir(plan, op.Sources, facadeDir, pkgName); err != nil {
			return nil, err
		}
	}

	return plan, nil
}
