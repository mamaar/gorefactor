package refactor

import (
	"errors"
	"path/filepath"
	"strings"
	"testing"

	pkgtypes "github.com/mamaar/gorefactor/pkg/types"
)

const genHeader = "// Code generated by x. DO NOT EDIT.\n\npackage p\n"

const genWrapper = `package p

func leaf() {}

type Wrapper struct{}

func (Wrapper) MapSearch() { leaf() }
`

const genBridge = genHeader + `
type Bridge interface{ MapSearch() }

type Adapter struct{ b Bridge }

func (a Adapter) MapSearch() { a.b.MapSearch() }
`

func bridgeFiles() map[string]string {
	return map[string]string{"p/w.go": genWrapper, "p/gen.go": genBridge}
}

// generatedRefusal runs the climb expecting the generated-code refusal.
func generatedRefusal(t *testing.T, files map[string]string, sourceFile, funcName string) *pkgtypes.RefactorError {
	t.Helper()
	err := threadErrStopping(t, files, sourceFile, funcName, true, nil)
	var re *pkgtypes.RefactorError
	if !errors.As(err, &re) || re.Type != pkgtypes.InvalidOperation {
		t.Fatalf("error is not an InvalidOperation RefactorError: %v", err)
	}
	if !strings.Contains(re.Message, "generated") || !strings.Contains(re.Message, "No changes were made.") {
		t.Fatalf("not the generated-code refusal: %v", err)
	}
	return re
}

func assertContains(t *testing.T, msg string, wants ...string) {
	t.Helper()
	for _, want := range wants {
		if !strings.Contains(msg, want) {
			t.Errorf("message lacks %q:\n%s", want, msg)
		}
	}
}

func assertNoStopSuggested(t *testing.T, msg string) {
	t.Helper()
	assertContains(t, msg, "No stop_at can avoid this")
	if strings.Contains(msg, "pass stop_at") {
		t.Errorf("message suggests a stop:\n%s", msg)
	}
}

func TestThreadContext_LoaderMarksGeneratedFiles(t *testing.T) {
	ws := buildScopeWorkspace(t, bridgeFiles())
	got := make(map[string]bool)
	for _, f := range allScopeTestFiles(findPackageByName(t, ws, "p")) {
		got[filepath.Base(f.Path)] = f.Generated
	}
	if !got["gen.go"] || got["w.go"] {
		t.Errorf("Generated = %v", got)
	}
}

func TestThreadContext_GeneratedInterfaceRefusesAndNamesTheImplementer(t *testing.T) {
	re := generatedRefusal(t, bridgeFiles(), "p/w.go", "leaf")
	want := "cannot thread context through leaf: the climb reaches generated code, which its generator " +
		"would overwrite: p/gen.go (p/gen.go:5: Bridge.MapSearch would gain a ctx parameter). To keep the " +
		`climb out of generated code, pass stop_at: ["p/w.go:Wrapper.MapSearch"]. No changes were made.`
	if re.Message != want {
		t.Errorf("message:\n got %s\nwant %s", re.Message, want)
	}
	if filepath.Base(re.File) != "gen.go" || re.Line != 5 {
		t.Errorf("location = %s:%d", re.File, re.Line)
	}
}

func TestThreadContext_SuggestedStopKeepsThePlanOutOfGeneratedCode(t *testing.T) {
	ws := buildScopeWorkspace(t, bridgeFiles())
	stops, err := resolveStopAt([]*pkgtypes.Workspace{ws}, []string{"p/w.go:Wrapper.MapSearch"})
	if err != nil {
		t.Fatal(err)
	}
	plan := threadPlanStopping(t, bridgeFiles(), "p/w.go", "leaf", stops)
	assertNames(t, gainingLabels(plan), []string{"leaf"}, "Funcs")
	for f, fd := range plan.Decls {
		if fd.File.Generated {
			t.Errorf("%s is declared in a generated file", funcLabel(f))
		}
	}
	for _, edit := range plan.ArgFor {
		if edit.Site.File.Generated {
			t.Errorf("call edit in generated file %s", edit.Site.File.Path)
		}
	}
}

func TestThreadContext_EveryCalledImplementerOfAGeneratedInterfaceIsListed(t *testing.T) {
	files := bridgeFiles()
	files["p/w.go"] += `
type Other struct{}

func (*Other) MapSearch() { leaf() }

type Idle struct{}

func (Idle) MapSearch() {}
`
	re := generatedRefusal(t, files, "p/w.go", "leaf")
	assertContains(t, re.Message, `pass stop_at: ["p/w.go:Other.MapSearch", "p/w.go:Wrapper.MapSearch"]`)
	if strings.Contains(re.Message, "Idle") {
		t.Errorf("an implementer the climb never enters is listed:\n%s", re.Message)
	}
}

func TestThreadContext_GeneratedImplementerListsEveryEntryOfItsInterfaceGroup(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": genWrapper + `
type Bridge interface{ MapSearch() }

type Other struct{}

func (Other) MapSearch() { leaf() }
`,
		"p/gen.go": genHeader + `
type Adapter struct{}

func (Adapter) MapSearch() {}
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message,
		"p/gen.go:7: Adapter.MapSearch would gain a ctx parameter",
		`pass stop_at: ["p/w.go:Other.MapSearch", "p/w.go:Wrapper.MapSearch"]`)
}

func TestThreadContext_FunctionCalledFromGeneratedCodeIsListed(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func leaf() {}

func helper() { leaf() }
`,
		"p/gen.go": genHeader + `
func genCaller() { helper() }
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message, "p/gen.go (p/gen.go:5: call to helper)", `pass stop_at: ["p/w.go:helper"]`)
}

func TestThreadContext_StopOnlyReachableThroughAnotherStopIsNotListed(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func leaf() {}

func helper() { leaf() }

func outer() { helper() }
`,
		"p/gen.go": genHeader + `
func genCaller() {
	helper()
	outer()
}
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message, `pass stop_at: ["p/w.go:helper"]`)
}

func TestThreadContext_GeneratedFilesAreListedSortedWithOneLocationEach(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func leaf() {}

func helper() { leaf() }
`,
		"p/zgen.go": genHeader + `
func zCaller() { helper() }
`,
		"p/agen.go": genHeader + `
func aCaller() {
	helper()
	helper()
}
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message, "p/agen.go (p/agen.go:6: call to helper); p/zgen.go (p/zgen.go:5: call to helper)")
	if filepath.Base(re.File) != "agen.go" || re.Line != 6 {
		t.Errorf("location = %s:%d", re.File, re.Line)
	}
}

func TestThreadContext_SeedCalledFromGeneratedCodeSuggestsNoStop(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func leaf() {}
`,
		"p/gen.go": genHeader + `
func genCaller() { leaf() }
`,
	}, "p/w.go", "leaf")
	want := "cannot thread context through leaf: the climb reaches generated code, which its generator " +
		"would overwrite: p/gen.go (p/gen.go:5: call to leaf). No stop_at can avoid this: leaf is the " +
		"function that gains the parameter; change the generator instead. No changes were made."
	if re.Message != want {
		t.Errorf("message:\n got %s\nwant %s", re.Message, want)
	}
}

func TestThreadContext_SeedDeclaredInGeneratedFileSuggestsNoStop(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func caller() { leaf() }
`,
		"p/gen.go": genHeader + `
func leaf() {}
`,
	}, "p/gen.go", "leaf")
	assertContains(t, re.Message, "p/gen.go:5: leaf would gain a ctx parameter")
	assertNoStopSuggested(t, re.Message)
}

func TestThreadContext_SeedSharingAnInterfaceWithGeneratedCodeSuggestsNoStop(t *testing.T) {
	re := generatedRefusal(t, bridgeFiles(), "p/w.go", "Wrapper.MapSearch")
	assertNoStopSuggested(t, re.Message)
}

const genValueUseWrapper = genWrapper + `
type Bridge interface{ MapSearch() }
`

func TestThreadContext_ValueUseOfGeneratedFunctionDoesNotMaskRefusal(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": genValueUseWrapper,
		"p/gen.go": genHeader + `
type Adapter struct{}

func (Adapter) MapSearch() {}

var search = Adapter.MapSearch
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message, `pass stop_at: ["p/w.go:Wrapper.MapSearch"]`)
}

func TestThreadContext_ValueUseInGeneratedCodeIsRefusedWithAStop(t *testing.T) {
	re := generatedRefusal(t, map[string]string{
		"p/w.go": `package p

func leaf() {}

func helper() { leaf() }
`,
		"p/gen.go": genHeader + `
var h = helper
`,
	}, "p/w.go", "leaf")
	assertContains(t, re.Message, "p/gen.go:5: helper used as a value", `pass stop_at: ["p/w.go:helper"]`)
}

func TestThreadContext_ValueUseInHandWrittenCodeStillAborts(t *testing.T) {
	err := threadErrStopping(t, map[string]string{
		"p/w.go": `package p

func leaf() {}

var h = leaf
`,
		"p/gen.go": genHeader + `
var g = leaf
`,
	}, "p/w.go", "leaf", true, nil)
	assertContains(t, err.Error(), "used as a value", "w.go")
}

func TestThreadContext_GeneratedFunctionAlreadyTakingCtxIsNotRefused(t *testing.T) {
	plan := threadPlanStopping(t, map[string]string{
		"p/w.go": `package p

import "context"

func caller() { seed(context.Background()) }
`,
		"p/gen.go": genHeader + `
import "context"

func seed(ctx context.Context) {}
`,
	}, "p/gen.go", "seed", nil)
	assertNames(t, gainingNames(plan), []string{"caller"}, "Funcs")
}
