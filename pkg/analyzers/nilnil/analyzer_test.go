package nilnil_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	gotypes "go/types"
	"reflect"
	"testing"

	"github.com/mamaar/gorefactor/pkg/analyzers"
	"github.com/mamaar/gorefactor/pkg/analyzers/nilnil"
	"github.com/mamaar/gorefactor/pkg/types"
)

func run(t *testing.T, src string) []*nilnil.Result {
	t.Helper()
	ws, _ := workspace(t, src)
	return analyze(t, ws)
}

func workspace(t *testing.T, src string) (*types.Workspace, *types.Package) {
	t.Helper()
	fset := token.NewFileSet()
	astFile, err := parser.ParseFile(fset, "testpkg.go", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}

	info := &gotypes.Info{
		Types: map[ast.Expr]gotypes.TypeAndValue{},
		Defs:  map[*ast.Ident]gotypes.Object{},
		Uses:  map[*ast.Ident]gotypes.Object{},
	}
	conf := gotypes.Config{Error: func(error) {}}
	typesPkg, _ := conf.Check("test/testpkg", fset, []*ast.File{astFile}, info)

	file := &types.File{Path: "testpkg.go", AST: astFile, OriginalContent: []byte(src)}
	pkg := &types.Package{
		Name:       "testpkg",
		Path:       "test/testpkg",
		ImportPath: "test/testpkg",
		Files:      map[string]*types.File{"testpkg.go": file},
		TypesPkg:   typesPkg,
		TypesInfo:  info,
	}
	file.Package = pkg
	return &types.Workspace{Packages: map[string]*types.Package{"test/testpkg": pkg}, FileSet: fset}, pkg
}

func analyze(t *testing.T, ws *types.Workspace) []*nilnil.Result {
	t.Helper()
	rr, err := analyzers.Run(ws, nilnil.Analyzer, "")
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	if rr.Result == nil {
		return nil
	}
	results, ok := rr.Result.([]*nilnil.Result)
	if !ok {
		t.Fatalf("unexpected result type %T", rr.Result)
	}
	return results
}

func TestNilNilReturnIsReported(t *testing.T) {
	results := run(t, `package testpkg

type T struct{}

func (r *T) Find(id int) (*T, error) {
	if id == 0 {
		return nil, nil
	}
	return r, nil
}
`)
	if len(results) != 1 {
		t.Fatalf("got %d results, want 1", len(results))
	}
	got := results[0]
	if got.Function != "T.Find" || got.InClosure {
		t.Errorf("function = %q in_closure = %v", got.Function, got.InClosure)
	}
	if !reflect.DeepEqual(got.ResultTypes, []string{"*T"}) {
		t.Errorf("result types = %v", got.ResultTypes)
	}
	if got.Line != 7 || got.Code != "return nil, nil" {
		t.Errorf("site = %d %q", got.Line, got.Code)
	}
}

func TestEveryNillableResultShapeIsReported(t *testing.T) {
	results := run(t, `package testpkg

type T struct{}

func Three() (*T, []int, error) { return nil, nil, nil }

func Slice() ([]int, error) { return nil, nil }

func Grouped() (a, b *T, err error) { return nil, nil, nil }
`)
	want := [][]string{{"*T", "[]int"}, {"[]int"}, {"*T", "*T"}}
	if len(results) != len(want) {
		t.Fatalf("got %d results, want %d", len(results), len(want))
	}
	for i, r := range results {
		if !reflect.DeepEqual(r.ResultTypes, want[i]) {
			t.Errorf("%s: result types = %v, want %v", r.Function, r.ResultTypes, want[i])
		}
	}
}

func TestOtherReturnsAreNotReported(t *testing.T) {
	results := run(t, `package testpkg

import "errors"

type T struct{}

func Err(err error) (*T, error) { return nil, err }

func Value() (*T, error) { return &T{}, nil }

func New() (*T, error) { return nil, errors.New("x") }

func NotError() (*T, *T) { return nil, nil }

func OnlyError() error { return nil }

func Bare() (t *T, err error) { return }

func Forward() (*T, error) { return Value() }

func (*T) Error() string { return "" }

func Shadowed() (*T, error) {
	nil := &T{}
	return nil, nil
}

var Literal = func() (*T, error) { return &T{}, nil }
`)
	if len(results) != 0 {
		t.Fatalf("got %+v, want none", results[0])
	}
}

func TestClosuresAreJudgedByTheirOwnSignature(t *testing.T) {
	results := run(t, `package testpkg

type T struct{}

func Outer() (*T, error) {
	f := func() error { return nil }
	return &T{}, f()
}

func Plain() {
	f := func() (*T, error) { return nil, nil }
	_, _ = f()
}

var PackageLevel = func() (*T, error) { return nil, nil }
`)
	want := []string{"Plain", ""}
	if len(results) != len(want) {
		t.Fatalf("got %d results, want %d", len(results), len(want))
	}
	for i, r := range results {
		if r.Function != want[i] || !r.InClosure {
			t.Errorf("results[%d]: function = %q in_closure = %v", i, r.Function, r.InClosure)
		}
	}
}

func TestPackageWithoutTypeInfoMatchesByName(t *testing.T) {
	ws, pkg := workspace(t, `package testpkg

type T struct{}

func Find() (*T, error) { return nil, nil }
`)
	pkg.TypesInfo = nil
	if results := analyze(t, ws); len(results) != 1 {
		t.Fatalf("got %d results, want 1", len(results))
	}
}

func TestGeneratedFilesAreSkipped(t *testing.T) {
	results := run(t, `// Code generated by mockgen. DO NOT EDIT.

package testpkg

type T struct{}

func Find() (*T, error) { return nil, nil }
`)
	if len(results) != 0 {
		t.Fatalf("got %+v, want none", results[0])
	}
}
