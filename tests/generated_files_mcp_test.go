const genModule = "module example.com/genmcp\n\ngo 1.21\n"

const genHeader = "// Code generated by tool. DO NOT EDIT.\n\n"

func readTree(t *testing.T, dir string) map[string]string {
	t.Helper()
	out := map[string]string{}
	err := filepath.Walk(dir, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		out[rel] = string(b)
		return nil
	})
	if err != nil {
		t.Fatalf("walk: %v", err)
	}
	return out
}

func renameWorkspace(t *testing.T) string {
	return writeInlineWorkspace(t, map[string]string{
		"go.mod": genModule,
		"lib/lib.go": `package lib

func Old() int { return 1 }
`,
		"lib/lib_gen.go": genHeader + `package lib

func UseOld() int { return Old() }
`,
	})
}

func TestGeneratedFile_RenameDryRunReportsBlockingIssue(t *testing.T) {
	dir := renameWorkspace(t)
	before := readTree(t, dir)
	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "rename_symbol", map[string]any{
		"symbol": "Old", "new_name": "New", "package": "lib", "dry_run": true,
	})
	out := decodePlanResult(t, res)
	if out.Success {
		t.Errorf("success = true, want false")
	}
	if !strings.Contains(out.BlockingIssue, "lib_gen.go") {
		t.Errorf("blocking_issue = %q, want it to name lib_gen.go", out.BlockingIssue)
	}
	if len(out.Diffs) == 0 {
		t.Errorf("diffs are empty, want the planned changes")
	}
	after := readTree(t, dir)
	if !equalTrees(before, after) {
		t.Errorf("dry run modified the workspace")
	}
}

func TestGeneratedFile_RenameApplyRefusedAndWritesNothing(t *testing.T) {
	dir := renameWorkspace(t)
	before := readTree(t, dir)
	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "rename_symbol", map[string]any{
		"symbol": "Old", "new_name": "New", "package": "lib",
	})
	if !res.IsError {
		t.Fatalf("expected an error result, got: %s", errText(res))
	}
	if !strings.Contains(errText(res), "lib_gen.go") {
		t.Errorf("error = %q, want it to name lib_gen.go", errText(res))
	}
	after := readTree(t, dir)
	if !equalTrees(before, after) {
		t.Errorf("workspace changed after a refused rename")
	}
}

func equalTrees(a, b map[string]string) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		w, ok := b[k]
		if !ok || w != v {
			return false
		}
	}
	return true
}

func TestGeneratedFile_TouchSkipsGeneratedFormatsHandWritten(t *testing.T) {
	genSrc := genHeader + "package lib\n\nfunc   G( ) {\n        }\n"
	handSrc := "package lib\n\nfunc   H( ) {\n        }\n"
	dir := writeInlineWorkspace(t, map[string]string{
		"go.mod":         genModule,
		"lib/lib_gen.go": genSrc,
		"lib/hand.go":    handSrc,
	})
	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "touch", map[string]any{"files": []string{"lib/lib_gen.go", "lib/hand.go"}})
	if res.IsError {
		t.Fatalf("touch error: %s", errText(res))
	}
	text := errText(res)
	if !strings.Contains(text, `"status": "skipped"`) || !strings.Contains(text, "generated-code header") {
		t.Errorf("touch result = %s, want lib_gen.go skipped with a generated-code reason", text)
	}
	got := readTree(t, dir)["lib/lib_gen.go"]
	if got != genSrc {
		t.Errorf("generated file changed:\n%s", got)
	}
	got = readTree(t, dir)["lib/hand.go"]
	if got == handSrc {
		t.Errorf("hand-written file was not formatted")
	}
}

const mockHeader = `// Code generated by MockGen. DO NOT EDIT.
// Source: thing.go
// The mock for package mock_x lives here.

// Package mock_x is a generated GoMock package.
`

func moveWorkspace(t *testing.T) string {
	return writeInlineWorkspace(t, map[string]string{
		"go.mod": genModule,
		"mock_x/thing_mock.go": mockHeader + `package mock_x

type Thing struct{}
`,
		"gen/dep.go": genHeader + `package gen

import "example.com/genmcp/mock_x"

var _ mock_x.Thing
`,
	})
}

func assertMovedMock(t *testing.T, dir, target, wantPkg string) {
	t.Helper()
	tree := readTree(t, dir)
	moved, ok := tree[filepath.Join(target, "thing_mock.go")]
	if !ok {
		t.Fatalf("moved file missing; tree: %v", keys(tree))
	}
	if !strings.HasPrefix(moved, "// Code generated by MockGen. DO NOT EDIT.\n") {
		t.Errorf("header is not line 1:\n%s", moved)
	}
	f, err := parser.ParseFile(token.NewFileSet(), "thing_mock.go", moved, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse moved file: %v", err)
	}
	if !ast.IsGenerated(f) {
		t.Errorf("moved file is no longer recognised as generated")
	}
	if f.Name.Name != wantPkg {
		t.Errorf("package clause = %q, want %q", f.Name.Name, wantPkg)
	}
	want := mockHeader + "package " + wantPkg + "\n\ntype Thing struct{}\n"
	if moved != want {
		t.Errorf("moved content =\n%s\nwant\n%s", moved, want)
	}
	dep := tree["gen/dep.go"]
	if !strings.Contains(dep, `"example.com/genmcp/`+filepath.ToSlash(target)+`"`) {
		t.Errorf("dependent import not rewritten:\n%s", dep)
	}
}

func keys(m map[string]string) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	return ks
}

func TestGeneratedFile_MovePackageRelocatesGeneratedFile(t *testing.T) {
	dir := moveWorkspace(t)
	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "move_package", map[string]any{
		"source_package": "mock_x", "target_package": "mocks/mock_y",
	})
	if res.IsError {
		t.Fatalf("move_package error: %s", errText(res))
	}
	assertMovedMock(t, dir, "mocks/mock_y", "mock_y")
}

func TestGeneratedFile_MoveDirRelocatesGeneratedFile(t *testing.T) {
	dir := moveWorkspace(t)
	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "move_dir", map[string]any{
		"source_dir": "mock_x", "target_dir": "mocks/mock_y",
	})
	if res.IsError {
		t.Fatalf("move_dir error: %s", errText(res))
	}
	assertMovedMock(t, dir, "mocks/mock_y", "mock_y")
}
