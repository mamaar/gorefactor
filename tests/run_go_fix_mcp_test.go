package tests_test

import (
	"context"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mamaar/gorefactor/tests/mcptest"
)

const goFixModule = "module example.com/gofixmcp\n\ngo 1.22\n"

const goFixContains = `package p

func hasA(xs []string) bool {
	for _, x := range xs {
		if x == "a" {
			return true
		}
	}

	return false
}

func hasB(xs []string) bool {
	for _, x := range xs {
		if x == "b" {
			return true
		}
	}

	return false
}
`

func TestRunGoFix_ImportAddingFixesAreAppliedAndCompile(t *testing.T) {
	dir := writeInlineWorkspace(t, map[string]string{"go.mod": goFixModule, "p/p.go": goFixContains})

	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	out := callJSON(t, sess, "run_go_fix", map[string]any{"analyzers": []string{"slicescontains"}})

	fixed, _ := out["fixed"].([]any)
	if len(fixed) != 2 {
		t.Fatalf("fixed = %v, want 2 slicescontains fixes (output: %v)", out["fixed"], out)
	}

	assertFileContains(t, dir, "p/p.go", `slices.Contains(xs, "a")`)
	assertFileContains(t, dir, "p/p.go", `slices.Contains(xs, "b")`)

	cmd := exec.Command("go", "build", "./...")
	cmd.Dir = dir

	b, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go build after fix: %v\n%s", err, b)
	}
}

func TestRunGoFix_GeneratedFileIsSkippedAndLeftUntouched(t *testing.T) {
	gen := "// Code generated by tool. DO NOT EDIT.\n\n" + strings.NewReplacer("hasA", "genA", "hasB", "genB").Replace(goFixContains)
	dir := writeInlineWorkspace(t, map[string]string{
		"go.mod":    goFixModule,
		"p/p.go":    goFixContains,
		"p/gen.go":  gen,
		"p/gen2.go": "package p\n",
	})

	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	out := callJSON(t, sess, "run_go_fix", map[string]any{"analyzers": []string{"slicescontains"}, "dry_run": true})

	skipped, _ := out["skipped"].([]any)
	if len(skipped) == 0 || !strings.Contains(skipped[0].(map[string]any)["reason"].(string), "generated file p/gen.go") {
		t.Errorf("skipped = %v, want a generated-file reason naming p/gen.go", out["skipped"])
	}

	if out["blocking_issue"] != nil {
		t.Errorf("blocking_issue = %v, want none", out["blocking_issue"])
	}

	got, err := os.ReadFile(filepath.Join(dir, "p/gen.go"))
	if err != nil || string(got) != gen {
		t.Errorf("generated file changed or unreadable: %v", err)
	}
}

func TestRunGoFix_UnknownAnalyzerListsValidNames(t *testing.T) {
	dir := writeInlineWorkspace(t, map[string]string{"go.mod": goFixModule, "p/p.go": "package p\n"})

	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	res := callTool(t, sess, "run_go_fix", map[string]any{"analyzers": []string{"nosuch"}})
	if !res.IsError {
		t.Fatalf("want error result, got %s", errText(res))
	}

	text := errText(res)
	if !strings.Contains(text, `unknown analyzer "nosuch"`) || !strings.Contains(text, "mapsloop") || !strings.Contains(text, "rangeint") {
		t.Errorf("error = %q, want unknown-name message listing valid analyzers", text)
	}
}

func TestRunGoFix_FixWithoutReplaceWordingIsNotRejectedAsSyntaxError(t *testing.T) {
	dir := writeInlineWorkspace(t, map[string]string{"go.mod": goFixModule, "p/p.go": `package p

import "strings"

func before(s string) string {
	i := strings.Index(s, ":")
	if i >= 0 {
		return s[:i]
	}

	return s
}
`})

	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	out := callJSON(t, sess, "run_go_fix", map[string]any{"analyzers": []string{"stringscut"}})

	assertFileContains(t, dir, "p/p.go", "strings.Cut(s")

	if out["changes_count"] == nil || out["changes_count"].(float64) == 0 {
		t.Errorf("output = %v, want applied changes", out)
	}
}

func TestRunGoFix_LineDirectiveDoesNotRedirectEdits(t *testing.T) {
	src := "package p\n\n//line foo.y:10\nfunc f(n int) {\n\tfor i := 0; i < n; i++ {\n\t\t_ = i\n\t}\n}\n"
	grammar := strings.Repeat("grammar line that is not go code\n", 10)
	dir := writeInlineWorkspace(t, map[string]string{"go.mod": goFixModule, "p/p.go": src, "p/foo.y": grammar})

	sess := mcptest.Dial(context.Background(), t, mcpTransport(), dir)
	defer sess.Close()

	callJSON(t, sess, "run_go_fix", map[string]any{"analyzers": []string{"rangeint"}})

	assertFileContains(t, dir, "p/p.go", "for i := range n {")

	got, err := os.ReadFile(filepath.Join(dir, "p/foo.y"))
	if err != nil || string(got) != grammar {
		t.Errorf("foo.y changed or unreadable: %v", err)
	}
}
